// Builds the self-contained root index.html from src/: bundles src/main.js
// with esbuild (IIFE, not minified) and inlines it, with the CSS of
// src/styles/, into the src/index.html shell.
//
//   node scripts/build.mjs           write index.html
//   node scripts/build.mjs --check   exit 1 if index.html differs from what src/ builds
//   node scripts/build.mjs --watch   rebuild whenever a file under src/ changes

import { existsSync, readdirSync, readFileSync, watch, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';
import * as esbuild from 'esbuild';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'src');
const STYLES = path.join(SRC, 'styles');
const OUT = path.join(ROOT, 'index.html');

const DOCTYPE = '<!DOCTYPE html>\n';
const GENERATED = '<!-- Generated by scripts/build.mjs from src/ — do not edit by hand. -->\n';
const CSS_MARKER = '<!-- @inline-css -->';
const JS_MARKER = '<!-- @inline-js -->';

/** Reads a text file with LF line endings, whatever the checkout uses. */
const readText = (file) => readFileSync(file, 'utf8').replace(/\r\n/g, '\n');

async function bundleJs() {
  const result = await esbuild.build({
    absWorkingDir: ROOT, // module comments in the bundle hold paths relative to it
    entryPoints: ['src/main.js'],
    bundle: true,
    format: 'iife',
    platform: 'browser',
    target: 'es2022',
    minify: false,
    charset: 'utf8',
    legalComments: 'none',
    write: false,
    logLevel: 'warning',
  });
  return result.outputFiles[0].text;
}

/** The files of src/styles/ in name order, with every @import line moved to the top. */
function concatCss() {
  const imports = [];
  const bodies = [];
  for (const file of readdirSync(STYLES)
    .filter((f) => f.endsWith('.css'))
    .sort()) {
    const lines = readText(path.join(STYLES, file)).split('\n');
    imports.push(...lines.filter((line) => line.startsWith('@import ')));
    bodies.push(
      lines
        .filter((line) => !line.startsWith('@import '))
        .join('\n')
        .trim(),
    );
  }
  return `${[...imports, ...bodies].join('\n\n')}\n`;
}

export async function build() {
  const shell = readText(path.join(SRC, 'index.html'));
  if (!shell.startsWith(DOCTYPE)) throw new Error(`src/index.html must start with ${DOCTYPE.trim()}`);
  for (const marker of [CSS_MARKER, JS_MARKER]) {
    if (shell.split(marker).length !== 2) throw new Error(`src/index.html must contain ${marker} exactly once`);
  }
  const js = await bundleJs();
  if (/<\/script/i.test(js)) throw new Error('the bundled JS contains "</script", which would end the inline script');
  const css = concatCss();
  if (/<\/style/i.test(css)) throw new Error('the CSS contains "</style", which would end the inline style');
  // Function replacements: the JS is full of "$" sequences that a replacement string would interpret
  return (
    DOCTYPE +
    GENERATED +
    shell
      .slice(DOCTYPE.length)
      .replace(CSS_MARKER, () => `<style>\n${css}</style>`)
      .replace(JS_MARKER, () => `<script>\n${js}</script>`)
  );
}

function sizes(html) {
  const kb = (bytes) => `${(bytes / 1000).toFixed(1)} kB`;
  const raw = Buffer.byteLength(html);
  return `${kb(raw)} raw, ${kb(gzipSync(html).length)} gzip`;
}

async function writeOnce() {
  const html = await build();
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : null;
  if (html === current) console.log(`index.html is up to date (${sizes(html)})`);
  else {
    writeFileSync(OUT, html);
    console.log(`wrote index.html (${sizes(html)})`);
  }
}

async function check() {
  const html = await build();
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : null;
  if (html !== current) {
    console.error('index.html is out of date with src/: run "npm run build" and commit the result.');
    process.exit(1);
  }
  console.log(`index.html is in sync with src/ (${sizes(html)})`);
}

function watchSrc() {
  let timer;
  const rebuild = () =>
    writeOnce().catch((error) => {
      console.error(`build failed: ${error.message}`);
    });
  rebuild();
  const watcher = watch(SRC, { recursive: true }, () => {
    clearTimeout(timer);
    timer = setTimeout(rebuild, 50);
  });
  watcher.on('error', (error) => {
    console.error(`cannot watch src/: ${error.message}`);
    process.exit(1);
  });
  console.log('watching src/ — reload index.html in the browser after each rebuild');
}

const mode = process.argv[2];
try {
  if (mode === '--check') await check();
  else if (mode === '--watch') watchSrc();
  else if (mode === undefined) await writeOnce();
  else throw new Error(`unknown option ${mode} (use --check or --watch)`);
} catch (error) {
  console.error(`build failed: ${error.message}`);
  process.exit(1);
}
